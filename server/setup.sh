#!/usr/bin/env bash
set -euo pipefail
umask 077
source_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
prefix="$HOME/.local"
config_dir="${XDG_CONFIG_HOME:-$HOME/.config}/ssh-image-paste"
state_dir="${XDG_STATE_HOME:-$HOME/.local/state}/ssh-image-paste"
display=:99
configure_shell=0
user_xclip=0
while (($#)); do
    case "$1" in
        --display) display=${2:?}; shift 2 ;;
        --prefix) prefix=${2:?}; shift 2 ;;
        --config-dir) config_dir=${2:?}; shift 2 ;;
        --state-dir) state_dir=${2:?}; shift 2 ;;
        --configure-shell) configure_shell=1; shift ;;
        --user-xclip) user_xclip=1; shift ;;
        -h|--help) echo "Usage: bash server/setup.sh [--display :99] [--configure-shell] [--user-xclip] [--prefix DIR] [--config-dir DIR] [--state-dir DIR]"; exit 0 ;;
        *) echo "Unknown option: $1" >&2; exit 2 ;;
    esac
done
[[ $display =~ ^:[0-9]+$ ]] || { echo 'Invalid display.' >&2; exit 2; }
export PATH="$prefix/bin:$HOME/.local/bin:$PATH"
if ! command -v xclip >/dev/null && ((user_xclip)); then
    command -v apt-get >/dev/null && command -v dpkg-deb >/dev/null || { echo '--user-xclip requires Debian/Ubuntu apt-get and dpkg-deb.' >&2; exit 1; }
    temporary=$(mktemp -d)
    trap 'rm -rf -- "$temporary"' EXIT
    (cd "$temporary" && apt-get download xclip)
    packages=("$temporary"/xclip_*.deb)
    [[ ${#packages[@]} == 1 && -f ${packages[0]} ]] || { echo 'Could not find downloaded xclip package.' >&2; exit 1; }
    dpkg-deb -x "${packages[0]}" "$temporary/extracted"
    mkdir -p "$prefix/bin"
    install -m 755 "$temporary/extracted/usr/bin/xclip" "$prefix/bin/xclip"
    if ldd "$prefix/bin/xclip" | grep -q 'not found'; then
        echo 'xclip still needs shared libraries; ask the server administrator to install its dependencies.' >&2
        exit 1
    fi
fi
missing=()
for tool in Xvfb xclip xauth xdpyinfo timeout flock openssl; do
    command -v "$tool" >/dev/null || missing+=("$tool")
done
if ((${#missing[@]})); then
    printf 'Missing dependencies: %s\n' "${missing[*]}" >&2
    echo 'Debian/Ubuntu administrator command: sudo apt-get install xvfb xclip xauth x11-utils util-linux openssl coreutils' >&2
    echo 'If only xclip is missing and its libraries exist: rerun with --user-xclip (no sudo).' >&2
    exit 1
fi
mkdir -p "$prefix/bin" "$config_dir" "$state_dir"
install -m 755 "$source_dir/clipboard-server.sh" "$prefix/bin/ssh-image-paste-server"
SSH_IMAGE_PASTE_STATE_DIR="$state_dir" "$prefix/bin/ssh-image-paste-server" --display "$display" ensure
env_file="$config_dir/env.sh"
{
    echo '# Generated by ssh-image-paste. Source this BEFORE starting your CLI.'
    printf 'export PATH=%q:"$PATH"\n' "$prefix/bin"
    printf 'export DISPLAY=%q\n' "$display"
    printf 'export SSH_IMAGE_PASTE_STATE_DIR=%q\n' "$state_dir"
    printf 'export XAUTHORITY=%q\n' "$state_dir/display-${display#:}/Xauthority"
    printf '%q --display %q ensure >/dev/null 2>&1\n' "$prefix/bin/ssh-image-paste-server" "$display"
} > "$env_file"
chmod 600 "$env_file"
if ((configure_shell)); then
    line="[ ! -r $(printf '%q' "$env_file") ] || . $(printf '%q' "$env_file")"
    touch "$HOME/.bashrc"
    if ! grep -Fxq -- "$line" "$HOME/.bashrc"; then
        cp -p "$HOME/.bashrc" "$config_dir/bashrc.before-$(date +%Y%m%d-%H%M%S)-$$"
        printf '\n# ssh-image-paste environment\n%s\n' "$line" >> "$HOME/.bashrc"
    fi
fi
printf '\nInstalled. In the terminal where you will start the CLI, run:\n  source %q\nThen RESTART the CLI. Existing processes do not inherit new environment variables.\n' "$env_file"
